CREATE OR REPLACE FUNCTION
  public.rnf10_registrar_historial_alerta()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_evento text;
  v_responsable uuid;
  v_responsable_tipo text;
  v_promedio_anterior numeric;
  v_promedio_nuevo numeric;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_evento := 'creada';
  ELSE
    IF ROW(
      OLD.estudiante_id,
      OLD.tipo,
      OLD.nivel,
      OLD.titulo,
      OLD.descripcion,
      OLD.estado,
      OLD.detalles,
      OLD.periodo_id,
      OLD.origen_tipo,
      OLD.origen_id,
      OLD.fecha_evento
    ) IS NOT DISTINCT FROM ROW(
      NEW.estudiante_id,
      NEW.tipo,
      NEW.nivel,
      NEW.titulo,
      NEW.descripcion,
      NEW.estado,
      NEW.detalles,
      NEW.periodo_id,
      NEW.origen_tipo,
      NEW.origen_id,
      NEW.fecha_evento
    ) THEN
      RETURN NEW;
    END IF;

    IF OLD.estado IS DISTINCT FROM NEW.estado
      AND NEW.estado = 'resuelta' THEN
      v_evento := 'resuelta';
    ELSIF OLD.estado = 'resuelta'
      AND NEW.estado IS DISTINCT FROM OLD.estado THEN
      v_evento := 'reabierta';
    ELSE
      v_evento := 'actualizada';
    END IF;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF NEW.cierre_manual_at IS DISTINCT FROM OLD.cierre_manual_at THEN
      v_responsable := NEW.cierre_manual_por;
    ELSIF NEW.seguimiento_iniciado_at
      IS DISTINCT FROM OLD.seguimiento_iniciado_at THEN
      v_responsable := NEW.seguimiento_iniciado_por;
    END IF;

    v_promedio_anterior := CASE
      WHEN (OLD.detalles->>'promedio') ~ '^[0-9]+([.][0-9]+)?$'
        THEN (OLD.detalles->>'promedio')::numeric
      ELSE NULL
    END;
  END IF;

  v_responsable_tipo := CASE
    WHEN v_responsable IS NULL THEN 'sistema'
    ELSE 'orientador'
  END;
  v_promedio_nuevo := CASE
    WHEN (NEW.detalles->>'promedio') ~ '^[0-9]+([.][0-9]+)?$'
      THEN (NEW.detalles->>'promedio')::numeric
    ELSE NULL
  END;

  INSERT INTO public.alertas_academicas_historial (
    alerta_id,
    estudiante_id,
    tipo_evento,
    estado_anterior,
    estado_nuevo,
    nivel_anterior,
    nivel_nuevo,
    promedio_anterior,
    promedio_nuevo,
    detalles_anteriores,
    detalles_nuevos,
    descripcion,
    responsable_id,
    responsable_tipo
  )
  VALUES (
    NEW.id,
    NEW.estudiante_id,
    v_evento,
    CASE WHEN TG_OP = 'UPDATE' THEN OLD.estado END,
    NEW.estado,
    CASE WHEN TG_OP = 'UPDATE' THEN OLD.nivel END,
    NEW.nivel,
    v_promedio_anterior,
    v_promedio_nuevo,
    CASE WHEN TG_OP = 'UPDATE' THEN OLD.detalles END,
    NEW.detalles,
    NEW.titulo || ': ' || NEW.descripcion,
    v_responsable,
    v_responsable_tipo
  );

  RETURN NEW;
END;
$$;

DO $$
BEGIN
  IF NOT EXISTS (
