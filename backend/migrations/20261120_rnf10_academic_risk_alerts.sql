  FROM public.alertas_academicas alerta
  JOIN public.actividades_academicas actividad
    ON actividad.id::text = alerta.origen_id
  WHERE alerta.estudiante_id = NEW.usuario_id
    AND alerta.tipo = 'actividad_incumplida'
    AND alerta.estado <> 'resuelta'
  ON CONFLICT (actividad_id, estudiante_id)
