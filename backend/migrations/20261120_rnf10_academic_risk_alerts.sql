  JOIN public.materia_grupo_periodo asignacion
    ON asignacion.id = actividad.materia_grupo_periodo_id
  WHERE actividad.estado = 'publicada'
    AND asignacion.grado_id = NEW.grado_id
    AND asignacion.grupo_id = NEW.grupo_id
  ON CONFLICT (actividad_id, estudiante_id)
  DO UPDATE SET
    estado = 'pendiente',
    intentos = 0,
    proximo_intento_at = EXCLUDED.proximo_intento_at,
    bloqueado_at = NULL,
    ultimo_error = NULL,
