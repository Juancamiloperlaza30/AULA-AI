CREATE OR REPLACE FUNCTION
  public.rnf10_encolar_estudiantes_actividad(
    p_actividad_id bigint,
    p_grado_id bigint,
    p_grupo_id bigint,
    p_proximo_intento_at timestamptz
  )
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  INSERT INTO public.actividad_alertas_pendientes (
    actividad_id,
    estudiante_id,
    estado,
    intentos,
    proximo_intento_at,
    bloqueado_at,
    ultimo_error,
    updated_at
  )
  SELECT
    p_actividad_id,
    estudiante.usuario_id,
    'pendiente',
    0,
    p_proximo_intento_at,
    NULL,
    NULL,
    now()
  FROM public.estudiantes estudiante
  WHERE estudiante.grado_id = p_grado_id
    AND estudiante.grupo_id = p_grupo_id
  ON CONFLICT (actividad_id, estudiante_id)
  DO UPDATE SET
    estado = 'pendiente',
    intentos = 0,
    proximo_intento_at = EXCLUDED.proximo_intento_at,
    bloqueado_at = NULL,
    ultimo_error = NULL,
    updated_at = now();
$$;

CREATE OR REPLACE FUNCTION
  public.rnf10_encolar_alertas_por_actividad()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_grado_id bigint;
  v_grupo_id bigint;
  v_proximo_intento timestamptz;
BEGIN
  IF TG_OP = 'DELETE' THEN
    SELECT grado_id, grupo_id
    INTO v_grado_id, v_grupo_id
    FROM public.materia_grupo_periodo
    WHERE id = OLD.materia_grupo_periodo_id;

    IF v_grado_id IS NOT NULL AND v_grupo_id IS NOT NULL THEN
      PERFORM public.rnf10_encolar_estudiantes_actividad(
        OLD.id,
        v_grado_id,
        v_grupo_id,
        now()
      );
    END IF;

    RETURN OLD;
  END IF;

  IF TG_OP = 'UPDATE'
    AND OLD.materia_grupo_periodo_id
      IS DISTINCT FROM NEW.materia_grupo_periodo_id THEN
    SELECT grado_id, grupo_id
    INTO v_grado_id, v_grupo_id
    FROM public.materia_grupo_periodo
    WHERE id = OLD.materia_grupo_periodo_id;

    IF v_grado_id IS NOT NULL AND v_grupo_id IS NOT NULL THEN
      PERFORM public.rnf10_encolar_estudiantes_actividad(
        NEW.id,
        v_grado_id,
        v_grupo_id,
        now()
      );
    END IF;
  END IF;

  SELECT grado_id, grupo_id
  INTO v_grado_id, v_grupo_id
  FROM public.materia_grupo_periodo
  WHERE id = NEW.materia_grupo_periodo_id;

  IF v_grado_id IS NOT NULL AND v_grupo_id IS NOT NULL THEN
    v_proximo_intento := CASE
      WHEN NEW.estado = 'publicada' THEN GREATEST(
        now(),
        COALESCE(NEW.fecha_publicacion, now()),
        COALESCE(NEW.fecha_entrega, now())
      )
      ELSE now()
    END;

    PERFORM public.rnf10_encolar_estudiantes_actividad(
      NEW.id,
      v_grado_id,
      v_grupo_id,
      v_proximo_intento
    );
  END IF;

  RETURN NEW;
END;
$$;

