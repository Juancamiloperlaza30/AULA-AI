CREATE OR REPLACE FUNCTION
  public.rnf10_encolar_alertas_por_cambio_asignacion()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_actividad record;
  v_proximo_intento timestamptz;
BEGIN
  IF OLD.grado_id IS NOT DISTINCT FROM NEW.grado_id
    AND OLD.grupo_id IS NOT DISTINCT FROM NEW.grupo_id
    AND OLD.materia_id IS NOT DISTINCT FROM NEW.materia_id THEN
    RETURN NEW;
  END IF;

  FOR v_actividad IN
    SELECT id, estado, fecha_publicacion, fecha_entrega
    FROM public.actividades_academicas
    WHERE materia_grupo_periodo_id = NEW.id
  LOOP
    IF OLD.grado_id IS NOT NULL AND OLD.grupo_id IS NOT NULL THEN
      PERFORM public.rnf10_encolar_estudiantes_actividad(
        v_actividad.id,
        OLD.grado_id,
        OLD.grupo_id,
        now()
      );
    END IF;

    IF NEW.grado_id IS NOT NULL AND NEW.grupo_id IS NOT NULL THEN
      v_proximo_intento := CASE
        WHEN v_actividad.estado = 'publicada' THEN GREATEST(
          now(),
          COALESCE(v_actividad.fecha_publicacion, now()),
          COALESCE(v_actividad.fecha_entrega, now())
        )
        ELSE now()
      END;

      PERFORM public.rnf10_encolar_estudiantes_actividad(
        v_actividad.id,
        NEW.grado_id,
        NEW.grupo_id,
        v_proximo_intento
      );
    END IF;
  END LOOP;

  RETURN NEW;
END;
$$;

